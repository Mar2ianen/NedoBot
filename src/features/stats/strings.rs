#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn russian_strings_are_nonempty() {
        let strings = StatsStrings::russian();
        for label in [
            strings.report_title,
            strings.messages,
            strings.top_writers,
            strings.quiet_ones,
            strings.user_stats_title,
            strings.moderation_line,
        ] {
            assert!(!label.trim().is_empty());
        }
    }

    #[test]
    fn english_renders_parallel_report() {
        use crate::features::stats::document::{Kv, Section};

        let strings = StatsStrings::english();
        assert_eq!(
            strings.period_title(crate::features::stats::types::StatsPeriod::Week),
            "week"
        );
        let section = Section {
            title: Some(strings.top_writers),
            rows: vec![Kv {
                label: strings.messages,
                value: "<b>5</b>".to_string(),
            }],
        };
        let html = section.emit_html();
        assert!(html.contains("Top writers"));
        assert!(html.contains("Messages: <b>5</b>"));
        assert!(!html.contains("Топ"));
    }
}
