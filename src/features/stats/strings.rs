    /// Period name for report titles. Kept here (not on the enum) so a
    /// future locale replaces wording without touching data types.
    pub fn period_title(&self, period: StatsPeriod) -> &'static str {
        match period {
            StatsPeriod::Day => self.period_day,
            StatsPeriod::Week => self.period_week,
            StatsPeriod::Month => self.period_month,
        }
    }

    /// Locale entry point for report wiring. Unknown locales fall back to
    /// Russian; startup validation rejects anything but `ru`/`en`.
    pub fn for_locale(locale: &str) -> Self {
        match locale {
            "en" => Self::english(),
            _ => Self::russian(),
        }
    }
